"""Generate the HTML named-reference table from WHATWG entities.json.

Usage: python3 generate_html_entities.py /path/to/entities.json
Source: https://html.spec.whatwg.org/entities.json
The source hash is recorded in the generated header for reproducibility.
"""
import hashlib
import json
import pathlib
import sys

source = pathlib.Path(sys.argv[1]).read_bytes()
entities = json.loads(source)
lines = [
    '// Copyright 2020-2026 Yonik Seeley and Luxir contributors',
    '// SPDX-License-Identifier: Apache-2.0',
    '// Generated by generate_html_entities.py; do not edit.',
    '// Source: https://html.spec.whatwg.org/entities.json',
    '// SHA256: ' + hashlib.sha256(source).hexdigest(),
    '#pragma once', '#include <string_view>',
    'namespace luxir::html_entities {',
    'struct Entry { std::string_view name, value; };',
    'inline constexpr Entry entries[] = {'
]
for name, entity in sorted(entities.items()):
    value = ''.join('\\x%02x' % b for b in entity['characters'].encode('utf-8'))
    lines.append('  {"%s", "%s"},' % (name[1:], value))
lines += ['};', 'inline constexpr size_t maxNameLength = %d;' % max(len(k)-1 for k in entities),
          '} // namespace luxir::html_entities', '']
pathlib.Path(__file__).with_name('HtmlEntities.h').write_text('\n'.join(lines))
